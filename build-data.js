#!/usr/bin/env node
/*
 * Re-generates data/bmw-models.js from data/bmw-models.json.
 *
 * data/bmw-models.json is the source of truth. The .js copy exists only so the
 * site also works when index.html is opened straight from disk (file://), where
 * browsers block fetch() of local JSON.
 *
 * Usage:  node tools/build-data.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'data');
const json = JSON.parse(fs.readFileSync(path.join(dir, 'bmw-models.json'), 'utf8'));

// Basic integrity checks so a typo in the JSON is caught before it ships.
const ids = new Set();
const problems = [];
for (const r of json.records) {
  if (ids.has(r.id)) problems.push('duplicate id: ' + r.id);
  ids.add(r.id);
  if (r.productionEnd !== null && r.productionEnd < r.productionStart) problems.push('end before start: ' + r.id);
}
for (const r of json.records) {
  for (const k of ['predecessorId', 'successorId', 'basedOn']) {
    if (r[k] && !ids.has(r[k])) problems.push(`${r.id}: ${k} points to missing id ${r[k]}`);
  }
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

json.meta.recordCount = json.records.length;
fs.writeFileSync(path.join(dir, 'bmw-models.json'), JSON.stringify(json, null, 1) + '\n');
fs.writeFileSync(
  path.join(dir, 'bmw-models.js'),
  '/* Generated by tools/build-data.js from bmw-models.json - do not edit by hand. */\n' +
    'window.BMW_DATA = ' + JSON.stringify(json) + ';\n'
);
console.log(`OK: ${json.records.length} records written to data/bmw-models.js`);
